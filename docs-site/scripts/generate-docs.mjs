function collectDocsPages() {
  const pages = [];
  function walk(dir) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) {
        walk(path);
      } else if (entry.name.endsWith('.mdx')) {
        const relativePath = relative(contentRoot, path).replace(/\\/g, '/');
        const slug = relativePath
          .replace(/\/index\.mdx$/, '/')
          .replace(/index\.mdx$/, '')
          .replace(/\.mdx$/, '/');
        const source = readFileSync(path, 'utf8');
        const title =
          frontmatterValue(source, 'title') ?? slug.replaceAll('/', ' ');
        const description = frontmatterValue(source, 'description') ?? '';
        pages.push({ slug: `/${slug}`, title, description, source, path });
      }
    }
  }
  walk(contentRoot);
  return pages.sort((a, b) => a.slug.localeCompare(b.slug));
}

function llmsPagePath(slug) {
  if (slug === '/') return '/llms/index.txt';
  return `/llms/${slug.replace(/^\/|\/$/g, '')}.txt`;
}

function stripFrontmatter(source) {
  return source
    .replace(/^---[\s\S]*?---\n/, '')
    .replace(/^\{\/\*[\s\S]*?\*\/\}\n/, '');
}

function qualifyRootRelativeMarkdownLinksForLLM(line) {
  const base = normalizedDocsBase();
  if (!base) return line;
  return line.replace(
    /\]\((\/(?!\/)[^)\s]+)([^)]*)\)/g,
    (match, path, suffix) => {
      if (path === base || path.startsWith(`${base}/`)) return match;
      return `](${base}${path}${suffix})`;
    },
  );
}

function expandRawCodeImports(source, pagePath) {
  const imports = new Map();
  let expanded = source.replace(
    /^import\s+(\w+)\s+from\s+['"](.+[?]raw)['"];\n?/gm,
    (_, name, importPath) => {
      const filePath = importPath.replace(/[?]raw$/, '');
      imports.set(name, readFileSync(join(pagePath, '..', filePath), 'utf8').trimEnd());
      return '';
    },
  );
  expanded = expanded.replace(/^import\s+.*\s+from\s+['"][^'"]+['"];\n?/gm, '');
  expanded = expanded.replace(
    /^<Code\s+code={(\w+)}\s+lang="([^"]+)"\s+title="([^"]+)"\s*\/>$/gm,
    (_, name, lang, title) => {
      const code = imports.get(name);
      if (!code) return '';
      return `\`\`\`${lang} title="${title}"\n${code}\n\`\`\``;
    },
  );
  return expanded;
}

/**
 * Markdown exports live at `<page>.md` and `llms/<page>.txt`, not at the HTML
 * directory route, so page-relative links must become absolute.
 */
function absolutizeRelativeMarkdownLinksForLLM(line, slug) {
  return line.replace(/\]\((?![a-z][a-z0-9+.-]*:|\/|#)([^)\s]+)([^)]*)\)/gi, (_match, path, suffix) => {
    const resolved = new URL(path, `https://docs.invalid${normalizedDocsBase()}${slug}`);
    const url = `${resolved.pathname}${resolved.search}${resolved.hash}`;
    return `](${docsSite ? `${docsSite.replace(/\/$/g, '')}${url}` : url}${suffix})`;
  });
}

function markdownForLLM(source, pagePath, slug) {
  let inCodeFence = false;
  const text = stripFrontmatter(expandRawCodeImports(source, pagePath))
    .replace(/<\/?(?:a|div|p|span|strong|code)[^>]*>/g, '')
    .split('\n')
    .map((line) => {
      if (line.trim().startsWith('```')) {
        inCodeFence = !inCodeFence;
        return line.trimEnd();
      }
      return inCodeFence
        ? line.trimEnd()
        : absolutizeRelativeMarkdownLinksForLLM(
            qualifyRootRelativeMarkdownLinksForLLM(line.trim()),
            slug,
          );
    })
    .join('\n')
    .replace(/^\s+$/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  return text;
}

function llmsPageBody(page) {
  return [
    `# ${page.title}`,
    '',
    `Source URL: ${publicDocsUrl(page.slug)}`,
    '',
    markdownForLLM(page.source, page.path, page.slug),
    '',
  ].join('\n');
}

function generateLLMSFiles() {
  ensureDir(publicRoot);
  const pages = collectDocsPages();
  const llmsRoot = join(publicRoot, 'llms');
  const llmsFullPath = join(publicRoot, 'llms-full.txt');
  if (existsSync(llmsRoot)) {
    rmSync(llmsRoot, { recursive: true, force: true });
  }
  if (existsSync(llmsFullPath)) {
    rmSync(llmsFullPath);
  }
  for (const page of pages) {
    writeGenerated(
      join(publicRoot, llmsPagePath(page.slug)),
      llmsPageBody(page),
    );
  }

  const llms = [
    '# SwiftAISDK documentation',
    '',
    'SwiftAISDK is a SwiftPM port of the provider-facing Vercel AI SDK.',
    '',
    `Current release: ${currentReleaseVersion()}`,
    '',
    `Every page is also available as Markdown: replace the trailing slash of a page URL with \`.md\` (for example ${publicDocsUrl('/core/tools.md')}).`,
    '',
    ...llmsSections.flatMap(([label, matches]) => {
      const sectionPages = pages.filter((page) => matches(page.slug));
      if (sectionPages.length === 0) return [];
      return [
        `## ${label}`,
        '',
        ...sectionPages.map(
          (page) =>
            `- [${page.title}](${publicDocsUrl(llmsPagePath(page.slug))}): ${page.description}`,
        ),
        '',
      ];
    }),
  ].join('\n');
  const unsectioned = pages.filter(
    (page) => !llmsSections.some(([, matches]) => matches(page.slug)),
  );
  if (unsectioned.length > 0) {
    throw new Error(`llms.txt has no section for: ${unsectioned.map((page) => page.slug).join(', ')}`);
  }

  writeGenerated(join(publicRoot, 'llms.txt'), llms);
}

