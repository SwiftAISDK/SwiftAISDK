function ensureDir(path) {
  mkdirSync(path, { recursive: true });
}

function writeGenerated(path, body) {
  ensureDir(join(path, '..'));
  writeFileSync(path, path.endsWith('.mdx') ? withGeneratedNotice(body) : body);
}

/** Marks generated MDX so editors and agents change the inputs instead. */
function withGeneratedNotice(body) {
  const notice =
    '{/* Generated by docs-site/scripts/generate-docs.mjs. Do not edit; see Docs/ProductDocumentation.md#generated-docs-site-pages. */}\n';
  const frontmatter = body.match(/^---\n[\s\S]*?\n---\n/);
  return frontmatter ? `${frontmatter[0]}${notice}${body.slice(frontmatter[0].length)}` : notice + body;
}

function normalizedDocsBase() {
  if (!docsBase || docsBase === '/') return '';
  return `/${docsBase.replace(/^\/|\/$/g, '')}`;
}

function publicDocsUrl(slug) {
  const path = `${normalizedDocsBase()}${slug}`;
  if (!docsSite) return path;
  return `${docsSite.replace(/\/$/g, '')}${path}`;
}

function referenceVersionNotice() {
  return `:::note[Development API reference]\nThese declarations follow the canonical repository's main branch. Match your installed versions to the published release documentation. See [Install](${publicDocsUrl('/getting-started/install/')}) for published packages and version-compatible examples.\n:::\n\n`;
}

