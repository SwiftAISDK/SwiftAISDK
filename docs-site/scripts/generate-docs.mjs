/** Package versions from the latest tested umbrella release record. */
function releasedPackageVersions() {
  const record = JSON.parse(
    readFileSync(join(repoRoot, 'Releases/umbrella', `${currentReleaseVersion()}.json`), 'utf8'),
  );
  return new Map(record.packages.map((entry) => [entry.package, entry.version]));
}

function providerInstall(row) {
  const catalog = catalogTools.readCatalog(repoRoot).catalog.packages;
  const pkg = catalog.find((p) => (p.capabilityRows ?? []).some((r) => r.providerID === row.providerID));
  const lines = ['## Package', ''];
  const versions = releasedPackageVersions();
  const version = versions.get(pkg?.id);
  const coreVersion = versions.get('swift-ai-core');
  // Only published packages get an installation snippet.
  if (!pkg || pkg.state !== 'extracted' || !version || !coreVersion) {
    lines.push('This provider is available through the complete `SwiftAISDK` umbrella (`import SwiftAISDK`).', '');
    return lines.join('\n') + '\n';
  }
  const module = pkg.modules[0].name;
  lines.push(
    `The complete \`SwiftAISDK\` umbrella (\`import SwiftAISDK\`) already includes this provider.`,
    `For a smaller dependency graph, add only core and \`${pkg.id}\`:`,
    '',
    '```swift',
    '// Package.swift',
    `.package(url: "https://github.com/SwiftAISDK/swift-ai-core.git", from: "${coreVersion}"),`,
    `.package(url: "${pkg.repository}", from: "${version}"),`,
    '',
    '// Target dependencies',
    '.product(name: "SwiftAI", package: "swift-ai-core"),',
    `.product(name: "${module}", package: "${pkg.id}"),`,
    '```',
    '',
    '```swift',
    'import SwiftAI',
    `import ${module}`,
    '```',
    '',
    `Versions shown are from the tested ${currentReleaseVersion()} release set. See [Install](../../getting-started/install/) for credentials and native factory settings.`,
    '',
  );
  return lines.join('\n') + '\n';
}

