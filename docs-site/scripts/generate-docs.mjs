function mdxText(value) {
  return String(value).replace(/[{}<>]/g, (c) => `\\${c}`);
}

function providerCredentials(row) {
  if (row.credentials.length === 0) {
    return '## Credentials\n\nThis provider does not read credentials from environment variables. Pass them in the provider settings; the guide below shows how.\n\n';
  }
  const rows = row.credentials
    .map((c) => `| \`${c.env}\` | ${mdxText(c.description)} |`)
    .join('\n');
  return `## Credentials\n\nThe default factory reads these environment variables. Explicit provider settings take precedence.\n\n| Variable | Purpose |\n| --- | --- |\n${rows}\n\n`;
}

function generateProviders() {
  const rows = readProviderRows();
  const providersRoot = join(contentRoot, 'providers');
  if (existsSync(providersRoot)) {
    for (const entry of readdirSync(providersRoot, { withFileTypes: true })) {
      if (entry.isFile() && entry.name !== 'index.mdx' && entry.name.endsWith('.mdx')) {
        rmSync(join(providersRoot, entry.name));
      }
    }
  }

  const capabilityList = capabilityGuides
    .map(([key, label, guide]) => {
      const count = rows.filter((row) => row[key]).length;
      return `| [${label}](../core/${guide}/) | ${count} |`;
    })
    .join('\n');

  const table = rows
    .map((row) => {
      const supported = capabilityGuides
        .filter(([key]) => row[key])
        .map(([, label]) => label)
        .join(', ');
      return `| [${mdxText(row.displayName)}](${providerSlug(row.providerID)}/) | \`${row.providerID}\` | ${row.factories} | ${supported} |`;
    })
    .join('\n');

  writeGenerated(
    join(contentRoot, 'providers/index.mdx'),
    `---\ntitle: Providers\ndescription: Compare SwiftAISDK providers by capability and open each provider's setup guide.\n---\n\nEach provider page shows its Swift package, credentials, factories, capabilities and provider-specific behavior. Every provider is also included in the complete \`SwiftAISDK\` umbrella package.\n\n| Capability | Providers |\n| --- | --- |\n${capabilityList}\n\n| Provider | Provider ID | Swift factory | Capabilities |\n| --- | --- | --- | --- |\n${table}\n\nThis page is generated from [Porting/packages.json](https://github.com/SwiftAISDK/SwiftAISDK/blob/main/Porting/packages.json) by \`npm --prefix docs-site run generate\`.\n`,
  );

  for (const row of rows) {
    const capabilities = capabilityGuides.filter(([key]) => row[key]);
    const capabilityListText = capabilities.length
      ? capabilities.map(([, label, guide]) => `- [${label}](../../core/${guide}/)`).join('\n')
      : '- No capabilities recorded yet.';
    const guide = providerGuide(row.providerID);
    const summary = row.notes ? `${mdxText(row.notes)}\n\n` : '';
    writeGenerated(
      join(contentRoot, `providers/${providerSlug(row.providerID)}.mdx`),
      `---\ntitle: ${yamlString(row.displayName)}\ndescription: ${yamlString(`Install and use ${row.displayName} (${row.upstreamPackage}) from Swift.`)}\n---\n\n${summary}Provider ID: \`${row.providerID}\` · Upstream package: \`${row.upstreamPackage}\`\n\n${providerInstall(row)}${providerCredentials(row)}## Factories\n\n${row.factories}\n\n## Capabilities\n\n${capabilityListText}\n${guide}\nFactory argument requirements are defined by the public Swift factory signatures. Use [Public symbols](../../reference/generated/public-symbols/) when you need the exact initializer or factory declaration.\n\nReturn to the [provider list](../).\n`,
    );
  }
}

// Package dumps omit dependency definitions. Read core and compatibility graphs,
// including extension graphs, so moving a declaration cannot erase its docs.
const runtimeCatalog = catalogTools.readCatalog(repoRoot).catalog.packages;
const runtimePackages = [
  { root: development.prepare(repoRoot), modules: ['SwiftAISDK'] },
  ...runtimeCatalog
    .filter(p => p.state === 'extracted')
    .map(p => ({ root: join(repoRoot, p.directory), modules: p.modules.map(m => m.name) })),
];
// Reuse compiled dependency modules across the sequential package dumps. Each
// dump still deletes and validates its own fresh runtime graphs before reading.
const symbolGraphBuild = join(repoRoot, '.build', 'documentation-symbolgraphs');
function symbolGraphFiles(pkg) {
  const found = [];
  function walk(dir) {
    for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const file = join(dir, entry.name);
      if (entry.isDirectory()) {
        if (!['checkouts', 'repositories', 'catalog-tools'].includes(entry.name) && !entry.name.startsWith('migration-')) walk(file);
      } else if (dir.endsWith('/symbolgraph') && pkg.modules.some(m => entry.name === `${m}.symbols.json` || entry.name.startsWith(`${m}@`))) {
        found.push(file);
      }
    }
  }
  if (existsSync(symbolGraphBuild)) walk(symbolGraphBuild);
  return found.sort();
}
function dumpSymbolGraphs() {
  const symbols = new Map();
  for (const pkg of runtimePackages) {
    for (const file of symbolGraphFiles(pkg)) rmSync(file);
    const result = spawnSync('swift', ['package', '--scratch-path', symbolGraphBuild, 'dump-symbol-graph',
      '--skip-synthesized-members', '--minimum-access-level', 'public', '--pretty-print'],
      { cwd: pkg.root, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 });
    const files = symbolGraphFiles(pkg);
    for (const module of pkg.modules) {
      if (!files.some(f => f.endsWith(`/${module}.symbols.json`))) {
        process.stdout.write(result.stdout ?? '');
        process.stderr.write(result.stderr ?? '');
        throw new Error(`Missing fresh symbol graph for ${module}`);
      }
    }
    // SwiftPM can fail to extract a test runner after emitting all library graphs.
    if (result.status !== 0) console.warn('SwiftPM reported a graph extraction error after all runtime graphs were emitted: ' + pkg.root);
    for (const file of files) {
      const graph = JSON.parse(readFileSync(file, 'utf8'));
      for (const symbol of graph.symbols) symbols.set(symbol.identifier.precise, { ...symbol, runtimeModule: graph.module.name });
    }
  }
  return [...symbols.values()];
}

function declaration(symbol) {
  const fragments =
    symbol.declarationFragments ?? symbol.names?.subHeading ?? [];
  return fragments.map((fragment) => fragment.spelling).join('');
}

function sourcePath(symbol) {
  const uri = symbol.location?.uri;
  if (!uri) return '';
  const filePath = fileURLToPath(uri);
  return relative(repoRoot, realpathSync(filePath));
}

function componentForPath(path) {
  const owner = runtimeCatalog.find(p => path.startsWith(p.directory + '/Sources/'));
  if (owner?.kind === 'mcp') return 'MCP';
  if (owner?.kind === 'ui') return 'Chat and UI messages';
  if (owner?.kind === 'provider') {
    const file = path.split('/').at(-1);
    return /Provider|Settings|Configuration/.test(file) ? 'Providers' : 'Provider models';
  }
  path = path.replace(/^.*\/Sources\/[^/]+\//, '');
  if (path.includes('/Providers/') || path.includes('Provider')) return 'Providers';
  if (path.includes('/Models/')) return 'Provider models';
  if (path.includes('MCP')) return 'MCP';
  if (path.includes('Middleware')) return 'Middleware';
  if (path.includes('AIChat') || path.includes('AIUI')) return 'Chat and UI messages';
  if (path.includes('Telemetry')) return 'Telemetry';
  if (path.includes('Object') || path.includes('Output')) return 'Structured output';
  if (path.includes('Tool')) return 'Tools';
  if (path.includes('Media') || path.includes('Image')) return 'Media';
  if (path.includes('Audio') || path.includes('Transcription') || path.includes('Speech')) return 'Audio';
  if (path.includes('Video') || path.includes('Reranking')) return 'Video and reranking';
  if (path.includes('Error')) return 'Errors';
  if (path.includes('Core') || path.includes('AI.swift') || path.includes('JSON') || path.includes('HTTP')) return 'Core runtime';
  return 'Core runtime';
}

function generateComponents(symbols) {
  const componentsRoot = join(contentRoot, 'components');
  if (existsSync(componentsRoot)) {
    rmSync(componentsRoot, { recursive: true, force: true });
  }
  const groups = new Map();
  for (const symbol of symbols) {
    const component = componentForPath(symbol.path);
    if (!groups.has(component)) groups.set(component, []);
    groups.get(component).push(symbol);
  }

  const overviewRows = [...groups.entries()]
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([component, componentSymbols]) => {
      const slug = slugify(component);
      return `| [${component}](${slug}/) | ${componentSymbols.length} |`;
    })
    .join('\n');

  writeGenerated(
    join(contentRoot, 'components/index.mdx'),
    `---\ntitle: Components\ndescription: Generated component map for SwiftAISDK public APIs.\n---\n\n${referenceVersionNotice()}SwiftAISDK groups public APIs into component areas so you can browse exact types without starting from the full symbol table.\n\n| Component | Public symbols |\n| --- | --- |\n${overviewRows}\n`,
  );

  for (const [component, componentSymbols] of [...groups.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    const kindCounts = new Map();
    for (const symbol of componentSymbols) {
      kindCounts.set(symbol.kind, (kindCounts.get(symbol.kind) ?? 0) + 1);
    }
    const counts = [...kindCounts.entries()]
      .sort((a, b) => a[0].localeCompare(b[0]))
      .map(([kind, count]) => `| ${kind} | ${count} |`)
      .join('\n');
    const symbolRows = componentSymbols
      .slice()
      .sort((a, b) => `${a.kind}:${a.title}`.localeCompare(`${b.kind}:${b.title}`))
      .map((symbol) => {
        const declarationText = symbol.declaration
          .replaceAll('|', '\\|')
          .replaceAll('\n', ' ');
        const path = symbol.path
          ? `[${symbol.path}](https://github.com/SwiftAISDK/SwiftAISDK/blob/main/${symbol.path})`
          : '';
        return `| ${symbol.kind} | \`${symbol.title.replaceAll('`', '')}\` | \`${declarationText.replaceAll('`', '')}\` | ${path} |`;
      })
      .join('\n');
    const guidePath = join(docsSiteRoot, 'scripts/component-guides', `${slugify(component)}.md`);
    const guide = existsSync(guidePath) ? `\n${readFileSync(guidePath, 'utf8')}` : '';
    writeGenerated(
      join(contentRoot, `components/${slugify(component)}.mdx`),
      `---\ntitle: ${component}\ndescription: Public SwiftAISDK APIs for ${component.toLowerCase()}.\n---\n\n${referenceVersionNotice()}${guide ? `${guide.trim()}\n\n` : ''}## Symbol counts\n\n| Symbol kind | Count |\n| --- | --- |\n${counts}\n\n## Public symbols\n\n| Kind | Symbol | Declaration | Source |\n| --- | --- | --- | --- |\n${symbolRows}\n`,
    );
  }
}

function generateReference() {
  const symbols = dumpSymbolGraphs()
    .filter((symbol) => !symbol.accessLevel || symbol.accessLevel === 'public')
    .map((symbol) => ({
      title: `${symbol.runtimeModule}.${symbol.names?.title ?? symbol.identifier?.precise ?? 'Symbol'}`,
      kind: symbol.kind?.displayName ?? symbol.kind?.identifier ?? 'symbol',
      declaration: declaration(symbol),
      path: sourcePath(symbol),
    }))
    .sort((a, b) => `${a.kind}:${a.title}`.localeCompare(`${b.kind}:${b.title}`));

  const symbolRows = symbols
    .map((symbol) => {
      const declarationText = symbol.declaration
        .replaceAll('|', '\\|')
        .replaceAll('\n', ' ');
      const path = symbol.path
        ? `[${symbol.path}](https://github.com/SwiftAISDK/SwiftAISDK/blob/main/${symbol.path})`
        : '';
      return `| ${symbol.kind} | \`${symbol.title.replaceAll('`', '')}\` | \`${declarationText.replaceAll('`', '')}\` | ${path} |`;
    })
    .join('\n');

  writeGenerated(
    join(contentRoot, 'reference/generated/public-symbols.mdx'),
    `---\ntitle: Public symbols\ndescription: Generated public SwiftAISDK symbol table.\n---\n\n${referenceVersionNotice()}This page is generated by \`npm --prefix docs-site run generate\` from \`swift package dump-symbol-graph\`.\n\n| Kind | Symbol | Declaration | Source |\n| --- | --- | --- | --- |\n${symbolRows}\n`,
  );

  generateComponents(symbols);
}

/** Reads a scalar frontmatter value, unquoting JSON-style generated strings. */
function frontmatterValue(source, key) {
  const raw = source.match(new RegExp(`^${key}:\\s*(.+)$`, 'm'))?.[1]?.trim();
  if (raw === undefined) return undefined;
  if (raw.startsWith('"')) {
    try {
      return JSON.parse(raw);
    } catch {
      return raw;
    }
  }
  return raw;
}

