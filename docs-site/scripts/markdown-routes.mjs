import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

/** `llms/core/tools.txt` → `core/tools.md`; `llms/index.txt` → `index.md`. */
function markdownPath(llmsRelativePath) {
  return llmsRelativePath.replace(/\.txt$/, '.md');
}

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? walk(path) : [path];
  });
}

/**
 * Serves every documentation page as Markdown at `<page>.md`, next to its HTML
 * route, using the LLM-readable text generated by `scripts/generate-docs.mjs`.
 */
export function markdownRoutes() {
  let base = '/';
  return {
    name: 'swiftaisdk-markdown-routes',
    hooks: {
      'astro:config:done': ({ config }) => {
        base = config.base.endsWith('/') ? config.base : `${config.base}/`;
      },
      'astro:server:setup': ({ server }) => {
        const llmsRoot = fileURLToPath(new URL('../public/llms/', import.meta.url));
        server.middlewares.use((request, response, next) => {
          const pathname = decodeURIComponent((request.url ?? '').split('?')[0]);
          if (!pathname.endsWith('.md') || !pathname.startsWith(base)) return next();
          const file = join(llmsRoot, pathname.slice(base.length).replace(/\.md$/, '.txt'));
          if (!file.startsWith(llmsRoot) || !existsSync(file)) return next();
          response.setHeader('Content-Type', 'text/markdown; charset=utf-8');
          response.end(readFileSync(file));
        });
      },
      'astro:build:done': ({ dir }) => {
        const outDir = fileURLToPath(dir);
        const llmsRoot = join(outDir, 'llms');
        if (!existsSync(llmsRoot)) return;
        for (const file of walk(llmsRoot).filter((path) => path.endsWith('.txt'))) {
          const target = join(outDir, markdownPath(relative(llmsRoot, file)));
          mkdirSync(dirname(target), { recursive: true });
          copyFileSync(file, target);
        }
      },
    },
  };
}
