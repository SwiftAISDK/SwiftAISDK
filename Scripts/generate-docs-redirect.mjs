#!/usr/bin/env node
// One-time Pages continuity after moving ozio/SwiftAISDK to SwiftAISDK/SwiftAISDK.
import fs from "node:fs";
import path from "node:path";
const output = process.argv[2];
if (!output || fs.existsSync(output)) throw Error("Pass a new output directory");
const built = path.resolve("docs-site/dist");
if (!fs.existsSync(path.join(built, "index.html"))) throw Error("Build documentation first");
const target = "https://swiftaisdk.github.io/SwiftAISDK/";
function write(file, contents) {
  const destination = path.join(output, file);
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, contents);
}
function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const file = path.join(dir, e.name);
    return e.isDirectory() ? walk(file) : [file];
  });
}
let pages = 0;
for (const file of walk(built).filter((f) => f.endsWith(".html") && !f.endsWith("/404.html"))) {
  const relative = path.relative(built, file).replaceAll(path.sep, "/");
  const url = target + relative.replace(/index\.html$/, "");
  write("SwiftAISDK/" + relative, `<!doctype html><html lang="en"><meta charset="utf-8"><title>SwiftAISDK documentation has moved</title><link rel="canonical" href="${url}"><meta http-equiv="refresh" content="0;url=${url}"><script>location.replace(${JSON.stringify(url)}+location.search+location.hash)</script><p>SwiftAISDK documentation has moved. <a href="${url}">Continue to this page</a>.</p></html>\n`);
  pages++;
}
// Machine readers cannot follow JavaScript. Preserve the generated text guides.
for (const file of walk(built).filter((f) => f.endsWith(".txt")))
  write("SwiftAISDK/" + path.relative(built, file), fs.readFileSync(file));
write("index.html", `<!doctype html><html lang="en"><meta charset="utf-8"><title>SwiftAISDK documentation</title><p><a href="${target}">SwiftAISDK documentation</a></p></html>\n`);
write("404.html", `<!doctype html><html lang="en"><meta charset="utf-8"><title>Page moved</title><script>if(location.pathname.startsWith('/SwiftAISDK/'))location.replace('https://swiftaisdk.github.io'+location.pathname+location.search+location.hash)</script><p><a href="${target}">SwiftAISDK documentation</a></p></html>\n`);
write(".nojekyll", "");
write("README.md", "# SwiftAISDK documentation redirects\n\nPreserves old documentation URLs after the canonical repository transfer. Generated by `Scripts/generate-docs-redirect.mjs` in [SwiftAISDK/SwiftAISDK](https://github.com/SwiftAISDK/SwiftAISDK). Do not recreate `ozio/SwiftAISDK`: that name is reserved for GitHub's repository redirect.\n");
write(".github/workflows/pages.yml", `name: Documentation redirects
on:
  push:
    branches: [main]
  workflow_dispatch:
permissions:
  contents: read
  pages: write
  id-token: write
concurrency:
  group: pages
  cancel-in-progress: false
jobs:
  deploy:
    runs-on: ubuntu-latest
    environment:
      name: github-pages
      url: \${{ steps.deployment.outputs.page_url }}
    steps:
      - uses: actions/checkout@v6
      - uses: actions/configure-pages@v6
      - uses: actions/upload-pages-artifact@v5
        with:
          path: .
          retention-days: 1
      - id: deployment
        uses: actions/deploy-pages@v5
`);
console.log(JSON.stringify({ pages, target, output: path.resolve(output) }));
