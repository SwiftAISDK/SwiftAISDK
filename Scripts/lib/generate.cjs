const fs = require("node:fs");
const path = require("node:path");
const { json, ensure, localPath, readCatalog } = require("./catalog.cjs");
const { renderCompatibility } = require("./compatibility.cjs");
const row = (values) => "| " + values.join(" | ") + " |";
const escape = (text) => text.replaceAll("|", "\\|");
const ticks = (text) => "`" + escape(text) + "`";
function exportInputRoots(p) {
  return [
    `${p.directory}/Package.swift`,
    ...p.modules.flatMap(m => [`${p.directory}/Sources/${m.name}`, `${p.directory}/Tests/${m.name}Tests`]),
    `${p.directory}/README.md`, `${p.directory}/Porting/map.json`,
    "LICENSE", ".github/workflows/package-check.yml",
  ];
}
function developmentManifest(data) {
  const q = JSON.stringify;
  const packages = data.catalog.packages.filter(p => p.state === "extracted");
  const products = packages.flatMap(p => p.modules.map(m =>
    `        .product(name: ${q(m.name)}, package: ${q(p.id)})`));
  return `// swift-tools-version: ${data.catalog.swiftToolsVersion}
// Generated by Scripts/sdk.mjs from the extracted package catalog.
// Development workspace only; tagged modular releases use remote version ranges.
import PackageDescription

let modules: [Target.Dependency] = [
${products.join(",\n")}
]

let package = Package(
    name: "SwiftAISDK",
    platforms: [.macOS(${q(data.catalog.platforms.macOS)}), .iOS(${q(data.catalog.platforms.iOS)})],
    products: [.library(name: "SwiftAISDK", targets: ["SwiftAISDK"])],
    dependencies: [
${packages.map(p => `        .package(path: ${q(p.directory)})`).join(",\n")}
    ],
    targets: [
        .target(name: "SwiftAISDK", dependencies: modules),
        .testTarget(name: "SwiftAISDKTests", dependencies: ["SwiftAISDK"] + modules, resources: [.process("Fixtures")])
    ],
    swiftLanguageModes: [.v6]
)
`;
}
function manifest(data, p, { distribution = false } = {}) {
  const q = JSON.stringify,
    c = data.catalog;
  const dependencies = p.dependencies
    .map(
      (d) => {
        const dependency = data.catalog.packages.find((x) => x.id === d.package);
        return !distribution && p.state === "extracted" && dependency.state === "extracted"
          ? `        .package(path: ${q("../" + dependency.id)})`
          : `        .package(url: ${q(dependency.repository)}, from: ${q(d.from)})`;
      },
    )
    .join(",\n");
  const targets = p.modules.map(
    (m) =>
      `        .target(name: ${q(m.name)}, dependencies: [${m.dependencies.map((d) => (d.includes("/") ? `.product(name: ${q(d.split("/")[1])}, package: ${q(d.split("/")[0])})` : q(d))).join(", ")}])`,
  );
  if (p.state !== "planned")
    targets.push(
      ...p.modules.map(
        (m) =>
          `        .testTarget(name: ${q(m.name + "Tests")}, dependencies: [${[...new Set([m.name, ...m.dependencies, ...(m.testDependencies || [])])].map((d) => (d.includes("/") ? `.product(name: ${q(d.split("/")[1])}, package: ${q(d.split("/")[0])})` : q(d))).join(", ")}]${m.testResources?.length ? `, resources: [${m.testResources.map(r => `.process(${q(r)})`).join(", ")}]` : ""})`,
      ),
    );
  return `// swift-tools-version: ${c.swiftToolsVersion}\n// Generated by Scripts/sdk.mjs. State: ${p.state}.\n// Canonical manifests use local extracted dependencies; distribution ranges require release verification.\nimport PackageDescription\n\nlet package = Package(\n    name: ${q(p.id)},\n    platforms: [.macOS(${q(c.platforms.macOS)}), .iOS(${q(c.platforms.iOS)})],\n    products: [\n${p.modules.map((m) => `        .library(name: ${q(m.name)}, targets: [${q(m.name)}])`).join(",\n")}\n    ],\n    dependencies: [\n${dependencies}\n    ],\n    targets: [\n${targets.join(",\n")}\n    ],\n    swiftLanguageModes: [.v6]\n)\n`;
}
function render(data) {
  const { root, catalog, lock, rows } = data,
    outputs = new Map();
  const template = (name) =>
    fs.readFileSync(path.join(root, "Porting/templates", name), "utf8");
  const swiftRows = rows
    .map(
      (r, i) =>
        "        providerRow(" +
        [
          JSON.stringify(r.providerID),
          JSON.stringify(r.upstreamPackage),
          JSON.stringify(r.factoryNames),
          `[${r.capabilities.map((c) => "." + c).join(", ")}]`,
          ...(r.files ? ["files: true"] : []),
          ...(r.skills ? ["skills: true"] : []),
          "notes: " + JSON.stringify(r.notes),
        ].join(", ") +
        ")" +
        (i < rows.length - 1 ? "," : ""),
    )
    .join("\n");
  outputs.set(
    "Sources/SwiftAISDK/Providers/ProviderCapabilityMatrix.swift",
    template("ProviderCapabilityMatrix.swift.in")
      .replace("@@DATE@@", catalog.snapshotDate)
      .replace("@@ROWS@@", swiftRows),
  );
  const compatibility = renderCompatibility(root);
  if (compatibility !== null) outputs.set("Sources/SwiftAISDK/Compatibility.swift", compatibility);
  const table = [
    row([
      "Upstream package",
      "Provider ID",
      "Swift factories",
      ...catalog.capabilities.map((c) => c.label),
      "F",
      "K",
    ]),
    row(Array(5 + catalog.capabilities.length).fill("---")),
    ...rows.map((r) =>
      row([
        ticks(r.upstreamPackage),
        ticks(r.providerID),
        r.factoryNames.map(ticks).join(", "),
        ...catalog.capabilities.map((c) =>
          r.capabilities.includes(c.name) ? "✅" : "",
        ),
        r.files ? "✅" : "",
        r.skills ? "✅" : "",
      ]),
    ),
  ].join("\n");
  const notes = [
    row(["Provider ID", "Note"]),
    row(["---", "---"]),
    ...rows.map((r) => row([ticks(r.providerID), escape(r.notes)])),
  ].join("\n");
  outputs.set(
    "Docs/ProviderCapabilityMatrix.md",
    template("capability-matrix.md")
      .replace("@@DATE@@", catalog.snapshotDate)
      .replace("@@TABLE@@", table)
      .replace("@@NOTES@@", notes),
  );
  const ledgerPath = "Docs/ProviderVersionLedger.md",
    ledger = fs.readFileSync(path.join(root, ledgerPath), "utf8");
  const ledgerTable = [
    row(["Package", "Version baseline", "Main Swift evidence"]),
    row(["---", "---", "---"]),
    ...lock.packages
      .filter((p) => p.ledgerKind === "provider" && p.reviewedVersion !== null)
      .map((p) => row([ticks(p.name), ticks(p.reviewedVersion), p.evidence])),
  ].join("\n");
  ensure(
    /\| Package \| Version baseline \| Main Swift evidence \|\n(?:\|[^\n]*\n?)+/.test(
      ledger,
    ),
    "Missing ledger table",
  );
  outputs.set(
    ledgerPath,
    ledger.replace(
      /\| Package \| Version baseline \| Main Swift evidence \|\n(?:\|[^\n]*\n?)+/,
      ledgerTable + "\n",
    ),
  );
  const corePath = "Docs/CoreV6Parity.md",
    core = fs.readFileSync(path.join(root, corePath), "utf8");
  const specs = lock.packages
    .filter((p) => p.ledgerKind === "core" && p.reviewedVersion !== null)
    .map((p) => "`" + p.name + "@" + p.reviewedVersion + "`");
  const snapshots = specs.slice(0, -1).join(", ") + ", and " + specs.at(-1);
  ensure(
    /snapshots, currently [\s\S]*?\.\n\nReferences:/.test(core),
    "Missing core snapshot span",
  );
  outputs.set(
    corePath,
    core.replace(
      /snapshots, currently [\s\S]*?\.\n\nReferences:/,
      "snapshots, currently " + snapshots + ".\n\nReferences:",
    ),
  );
  const matrix = [],
    exports = [],
    index = [
      "# Modular package catalog",
      "",
      "Generated from `Porting/packages.json`. All package states are explicit; planned/scaffold manifests are not published installation endpoints.",
      "",
      "| Package | State | Modules | Upstream |",
      "| --- | --- | --- | --- |",
    ];
  for (const p of catalog.packages) {
    outputs.set(`${p.directory}/Package.swift`, manifest(data, p));
    index.push(
      row([
        ticks(p.id),
        p.state,
        p.modules.map((m) => ticks(m.name)).join(", "),
        p.upstream.map(ticks).join(", "),
      ]),
    );
    matrix.push({
      package: p.id,
      directory: p.directory,
      state: p.state,
      independentBuildReady: p.state === "extracted",
      command:
        p.state === "extracted"
          ? `swift test --package-path ${p.directory}`
          : null,
      upstream: p.upstream,
    });
    exports.push({
      package: p.id,
      repository: p.repository,
      releaseReady: false,
      gate: "Committed source, reviewed evidence, M4 rehearsal and M5 remote publication verification required",
      inputs: exportInputRoots(p),
      dependencies: p.dependencies,
    });
  }
  if (catalog.packages.some(p => p.state === "extracted")) {
    outputs.set("Package.swift", developmentManifest(data));
    outputs.set("Sources/SwiftAISDK/ProviderExports.swift",
      "// Generated by Scripts/sdk.mjs from the extracted package catalog.\n" +
      catalog.packages.filter(p => p.state === "extracted")
        .flatMap(p => p.modules.map(m => `@_exported import ${m.name}`)).join("\n") + "\n");
  }
  outputs.set("Docs/PackageCatalog.md", index.join("\n") + "\n");
  outputs.set(
    "Porting/Generated/ci-matrix.json",
    json({ schemaVersion: 1, include: matrix }),
  );
  outputs.set(
    "Porting/Generated/exports.json",
    json({
      schemaVersion: 1,
      scope:
        "Export input plan only; no published packages or release readiness implied",
      packages: exports,
    }),
  );
  outputs.set(
    "Porting/Generated/development-workspace.json",
    json({
      schemaVersion: 1,
      scope:
        "Identity-preserving local override inputs; executable development workspace is validated in M2/M3",
      dependencies: catalog.packages.map((p) => ({
        identity: p.id,
        path: p.directory,
        remote: p.repository,
      })),
      releaseOrder: data.order,
    }),
  );
  return outputs;
}
function generate(root, check = false) {
  const data = readCatalog(root),
    outputs = render(data),
    indexFile = "Porting/Generated/files.json";
  outputs.set(indexFile, json([...outputs.keys(), indexFile].sort()));
  const stale = [],
    changes = [];
  if (fs.existsSync(path.join(root, indexFile)))
    for (const file of JSON.parse(
      fs.readFileSync(path.join(root, indexFile), "utf8"),
    )) {
      localPath(root, file);
      if (!outputs.has(file) && fs.existsSync(path.join(root, file)))
        stale.push(file);
    }
  ensure(
    stale.length === 0,
    `Obsolete generated files require explicit removal: ${stale.join(", ")}`,
  );
  for (const [file, content] of outputs) {
    const full = localPath(root, file);
    if (!fs.existsSync(full) || fs.readFileSync(full, "utf8") !== content)
      changes.push(file);
  }
  if (check)
    ensure(
      changes.length === 0,
      `Generated files differ: ${changes.join(", ")}`,
    );
  else
    for (const file of changes) {
      const full = localPath(root, file);
      fs.mkdirSync(path.dirname(full), { recursive: true });
      fs.writeFileSync(full + ".sdk-tmp", outputs.get(file));
      fs.renameSync(full + ".sdk-tmp", full);
    }
  return {
    packages: data.catalog.packages.length,
    upstream: data.lock.packages.length,
    capabilities: data.rows.length,
    changed: changes,
  };
}
function affected(data, files) {
  const selected = new Set(),
    reasons = [];
  for (const file of files) {
    localPath(data.root, file);
    let owners = [];
    for (const p of data.catalog.packages) {
      const map = data.maps.get(p.id);
      if (
        file.startsWith(p.directory + "/") ||
        p.guides.includes(file) ||
        Object.values(map.swift)
          .flat()
          .some((f) => file === f || file.startsWith(f + "/"))
      )
        owners.push(p.id);
    }
    if (
      owners.length === 0 ||
      owners.some((id) => data.maps.get(id).status !== "reviewed")
    ) {
      owners = data.catalog.packages.map((p) => p.id);
      reasons.push(`${file}: unknown/coarse mapping; widened to all packages`);
    }
    owners.forEach((id) => selected.add(id));
  }
  let changed = true;
  while (changed) {
    changed = false;
    for (const p of data.catalog.packages)
      if (
        !selected.has(p.id) &&
        p.dependencies.some((d) => selected.has(d.package))
      ) {
        selected.add(p.id);
        changed = true;
      }
  }
  return {
    execution: "selection-only",
    reason: reasons,
    packages: data.order.filter((id) => selected.has(id)),
    requiredCurrentCommand: "node Scripts/test-packages.mjs",
  };
}
module.exports = { render, generate, manifest, affected, exportInputRoots };
