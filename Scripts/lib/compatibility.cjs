// Generate a forwarding namespace rather than a second handwritten facade.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {execFileSync} = require('node:child_process');
function renderCompatibility(root) {
  const sourceRoot=path.join(root,'Packages/swift-ai-core/Sources/SwiftAI');
  if(!fs.existsSync(sourceRoot)) return null;
  const tool=path.join(root,'Scripts/Tools/CoreAPISurface.swift');
  const compiler=execFileSync('xcrun',['--find','swiftc'],{encoding:'utf8'}).trim();
  const host=path.resolve(compiler,'../../lib/swift/host');
  const version=execFileSync(compiler,['--version'],{encoding:'utf8',stdio:['ignore','pipe','pipe']});
  const sdk=execFileSync('xcrun',['--sdk','macosx','--show-sdk-path'],{encoding:'utf8'}).trim();
  const hash=crypto.createHash('sha256').update(fs.readFileSync(tool)).update(compiler).update(version).update(sdk).digest('hex');
  const cache=path.join(root,'.build/catalog-tools',hash),binary=path.join(cache,'core-api-surface');
  if(!fs.existsSync(binary)) {
    fs.mkdirSync(cache,{recursive:true});
    execFileSync(compiler,['-sdk',sdk,'-I',host,'-L',host,'-lSwiftSyntax','-lSwiftParser','-Xlinker','-rpath','-Xlinker',host,tool,'-o',binary],{stdio:['ignore','pipe','pipe']});
  }
  const sources=fs.readdirSync(sourceRoot).filter(f=>f.endsWith('.swift')).sort().map(f=>path.join(sourceRoot,f));
  const methods=JSON.parse(execFileSync(binary,sources,{encoding:'utf8',maxBuffer:16*1024*1024}));
  const keys=new Set();
  const argumentList = method => method.parameters.map(p => {
    let value=(p.type.startsWith('inout ')?'&':'')+p.name;
    if(method.scope==='AI' && p.type==='AIDecisionModelReference')value=`.model(try compatibilityResolveDecisionModel(${p.name}))`;
    if(method.scope==='AI' && p.type==='AIEvaluationModelReference')value=`.model(try compatibilityResolveEvaluationModel(${p.name}))`;
    return (p.label==='_'?'':p.label+': ')+value;
  }).join(', ');
  const render = method => {
    const key=method.scope+method.kind+method.name+JSON.stringify(method.parameters?.map(p=>[p.label,p.type]));
    if(keys.has(key))throw new Error('Duplicate compatibility signature: '+key); keys.add(key);
    if(method.kind==='property')return `    public var ${method.name}: ${method.type} { base.${method.name} }`;
    if(method.kind==='initializer') {
      const params=new Map(method.parameters.map(p=>[p.name,p]));
      const names=['providerID','languageModels','embeddingModels','imageModels','transcriptionModels','speechModels','videoModels','rerankingModels','decisionModels','evaluationModels','files','skills','fallbackProvider'];
      const args=names.map(name=>{
        const p=params.get(name);
        let value=p?name:'[:]';
        if(p?.type==='[String: any AIEvaluationModelV4]')value+=' .mapValues { .model($0) }';
        return name+': '+value;
      });
      args.push('resolveDecisionModelID: { try AIDefaultProvider.resolveDecisionModel($0) }','resolveEvaluationModelID: { try AIDefaultProvider.resolveEvaluationModel($0) }');
      return method.signature.trimEnd()+` {\n        self.base = SwiftAI.AICustomProvider(${args.join(', ')})\n    }`;
    }
    const effects=(method.throws?'try ':'')+(method.async?'await ':'');
    const target=method.scope==='AI'?`SwiftAI.AI.${method.name}`:method.scope==='AICustomProvider'?`base.${method.name}`:method.name==='customProvider'?'AICustomProvider':`SwiftAI.AIProviders.${method.name}`;
    return method.signature.trimEnd()+` {\n        return ${effects}${target}(${argumentList(method)})\n    }`;
  };
  const byScope=scope=>methods.filter(m=>m.scope===scope).map(render).join('\n');
  return `// Generated by Scripts/sdk.mjs from core public signatures.\n// Legacy provider resolution stays here; runtime implementation stays in core.\nimport Foundation\n@_exported import SwiftAI\n@_exported import SwiftAIProvider\n@_exported import SwiftAIProviderUtilities\n@_exported import SwiftAITransport\n\npublic enum AI {}\npublic enum AIProviders {}\n\nextension AI {\n${byScope('AI')}\n}\n\npublic final class AICustomProvider: AIFileProvider, AISkillsProvider, AIEvaluationProvider, AIDecisionProvider, Sendable {\n    private let base: SwiftAI.AICustomProvider\n${byScope('AICustomProvider')}\n}\n\n${byScope('global')}\n\nextension AIProviders {\n${byScope('AIProviders')}\n}\n`;
}
module.exports={renderCompatibility};
